#use of \n is to print the next string in new line
a = "Jamshaid is a good boy\nBut not a good student"
print(a)
# use of \t is to print the next string in new line with a tab space
b = "Jamshaid is a good boy\tBut not a good student"   
print(b)
# To print the backslash(\) in the string we use double backslash(\\)
c = "Jamshaid is a good boy\\But not a good student"   
print(c)
# To print the double quote(") in the string we use backslash(\)
d = "Jamshaid is a good boy\"But not a good student\""
print(d)
# some other escape sequences are:
# \n    New line
# \t    Tab
# \\    Backslash
# \"    Double quote
# \'    Single quote
# \r    Carriage return
# \b    Backspace
# \f    Form feed
# \v    Vertical tab
# \a    Alert/bell
# \0    Null character

